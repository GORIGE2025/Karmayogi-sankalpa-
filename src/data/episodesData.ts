export function formatTime(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}

export function getPhaseIndexAtSecond(sec: number): number {
  let p = 0;
  PHASES.forEach((x, i) => {
    if (sec >= x[0]) p = i;
  });
  return p;
}

export interface StageNarration {
  caption: string;
  speechText: string;
  speechRate: number;
  phaseIndex: number;
}

export function getStageNarration(epIndex: number, r: number): StageNarration {
  const d = EPISODES[epIndex];
  const n = epIndex + 1;
  const phaseIndex = getPhaseIndexAtSecond(r);

  if (r < 8) {
    const speechText = `ప్రశ్న ${n}. ${d.title}. మీరు ఏమి చేస్తారు?`;
    return {
      caption: speechText,
      speechText,
      speechRate: 1,
      phaseIndex,
    };
  }
  if (r < 34) {
    return {
      caption:
        d.s.length > 140
          ? 'పరిస్థితిని జాగ్రత్తగా చదివి, మీరు ఏమి చేస్తారో ఆలోచించండి.'
          : d.s,
      speechText: d.s,
      speechRate: 1.12,
      phaseIndex,
    };
  }
  if (r < 104) {
    const j = Math.min(4, Math.floor((r - 34) / 14));
    const speechText = `ఎంపిక ${OPTION_LETTERS[j]}. ${d.l[j]}`;
    return {
      caption: speechText,
      speechText,
      speechRate: 1,
      phaseIndex,
    };
  }
  if (r < 114) {
    const speechText = `ఈ ప్రశ్న ${d.attr} గురించి. మీరు ఏ ఎంపిక చేస్తారు? కామెంట్లలో చెప్పండి.`;
    return {
      caption: speechText,
      speechText,
      speechRate: 1,
      phaseIndex,
    };
  }
  const nx = EPISODES[epIndex + 1];
  const speechText = nx
    ? `ఉపయోగపడితే లైక్, సబ్‌స్క్రైబ్ చేయండి. తర్వాత ప్రశ్న ${n + 1}.`
    : 'iGOT కర్మయోగిలో మీ బేస్‌లైన్ ప్రశ్నావళి పూర్తి చేసి 100 కర్మ పాయింట్లు పొందండి.';
  return {
    caption: speechText,
    speechText,
    speechRate: 1,
    phaseIndex,
  };
}

